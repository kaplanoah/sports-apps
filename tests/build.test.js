import test, { mock } from "node:test";
import assert from "node:assert/strict";
import { cpSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { findPageRoot, listApps, listServices } from "../worker/apps.mjs";
import {
  buildWorker,
  describeBanner,
  labelChannelFiles,
  listBundledFiles,
  readRelease,
} from "../worker/build.mjs";
import { createServiceRoots } from "./service-roots.js";

const BUILT_AT = new Date("2026-10-07T12:00:00Z");
const RELEASE = {
  version: "2.32.2-beta",
  commit: "b102733",
  builtAt: BUILT_AT.toISOString(),
  label: "beta",
};

const readManifest = (files) => JSON.parse(files["manifest.webmanifest"].text);
const readHomeScreenTitle = (files, path) =>
  files[path].text.match(/<meta name="apple-mobile-web-app-title" content="([^"]+)"/)[1];

test("a built Worker names the folders it's built from, a page for an app and none for a service", () => {
  const { roots, remove } = createServiceRoots();
  try {
    assert.equal(
      describeBanner("mlb", roots.servicesRoot),
      "// Generated by worker/build.mjs from apps/mlb/worker/src/ and apps/mlb/page/. Edit those and rebuild.",
    );
    assert.equal(
      describeBanner("accounts", roots.servicesRoot),
      "// Generated by worker/build.mjs from services/accounts/worker/src/. Edit those and rebuild.",
    );
  } finally {
    remove();
  }
});

test("a beta page names itself beta on the Home Screen, and production's doesn't", () => {
  for (const app of listApps()) {
    const production = listBundledFiles(app, { ...RELEASE, version: "2.32.2" });
    const name = readManifest(production).short_name;
    assert.equal(readManifest(production).name, name, app);
    assert.equal(readHomeScreenTitle(production, "index.html"), name, app);
    assert.equal(readHomeScreenTitle(production, "gate.html"), name, app);

    const beta = listBundledFiles(app, RELEASE, "beta");
    assert.equal(readManifest(beta).name, `${name} beta`, app);
    assert.equal(readManifest(beta).short_name, `${name} beta`, app);
    assert.equal(readHomeScreenTitle(beta, "index.html"), `${name} beta`, app);
    assert.equal(readHomeScreenTitle(beta, "gate.html"), `${name} beta`, app);
  }
});

test("labeling leaves every other file as it was", () => {
  const files = {
    "manifest.webmanifest": { contentType: "application/manifest+json", text: '{"name":"X"}' },
    "styles.css": { contentType: "text/css", text: "body {}" },
    "icon.png": { contentType: "image/png", base64: "AAAA" },
  };
  assert.equal(labelChannelFiles(files, null), files);
  const labeled = labelChannelFiles(files, "beta");
  assert.equal(labeled["styles.css"], files["styles.css"]);
  assert.equal(labeled["icon.png"], files["icon.png"]);
});

/** @param {Record<string, string>} answers git's answer to each command, by its arguments */
const createGit = (answers) => (args) => {
  const answer = answers[args.join(" ")];
  if (answer === undefined) throw new Error(`unexpected git ${args.join(" ")}`);
  return answer;
};

test("a beta release counts main's version where its branch left it, and says beta", () => {
  const base = "f".repeat(40);
  const git = createGit({
    "log -1 --format=%h": "b102733\n",
    "merge-base HEAD origin/main": `${base}\n`,
    [`merge-base --is-ancestor 3cf716ccf7c056c3e598a7e4ce82c0c591ac210c ${base}`]: "",
    [`log --first-parent --reverse --format=\x1e%s --name-only --diff-merges=first-parent --no-renames 3cf716ccf7c056c3e598a7e4ce82c0c591ac210c..${base}`]:
      "\x1efeat: something new\napps/mlb/page/js/app.js\n",
  });
  assert.deepEqual(readRelease("mlb", git, BUILT_AT, "beta"), {
    version: "2.33.0-beta",
    commit: "b102733",
    builtAt: BUILT_AT.toISOString(),
    label: "beta",
  });
});

test("a production release has no label, so its page shows no channel tag", () => {
  const git = createGit({
    "log -1 --format=%h": "b102733\n",
    "merge-base --is-ancestor 3cf716ccf7c056c3e598a7e4ce82c0c591ac210c HEAD": "",
    "log --first-parent --reverse --format=\x1e%s --name-only --diff-merges=first-parent --no-renames 3cf716ccf7c056c3e598a7e4ce82c0c591ac210c..HEAD":
      "\x1efeat: something new\napps/mlb/page/js/app.js\n",
  });
  assert.deepEqual(readRelease("mlb", git, BUILT_AT), {
    version: "2.33.0",
    commit: "b102733",
    builtAt: BUILT_AT.toISOString(),
    label: null,
  });
});

const TUNING_ROUND = {
  name: "Corners",
  values: [{ property: "--radius-control", label: "Button corners", min: 0, max: 12, step: 1 }],
};
const TUNING_TAGS = [
  /<script type="application\/json" id="tuningRound">/,
  /<link rel="stylesheet" href="release\/b102733\/shared\/tuning-panel\.css"/,
  /<script type="module" src="release\/b102733\/shared\/tuning-panel\.js"/,
];

/**
 * A copy of an app's page with a tuning round open, as the apps' folder a build reads from.
 * @param {string} app
 */
function createTuningRoot(app) {
  const folder = mkdtempSync(path.join(tmpdir(), "apps-"));
  cpSync(findPageRoot(app), path.join(folder, app, "page"), { recursive: true });
  writeFileSync(path.join(folder, app, "page/tuning-round.json"), JSON.stringify(TUNING_ROUND));
  return {
    appsRoot: pathToFileURL(`${folder}/`),
    remove: () => rmSync(folder, { recursive: true, force: true }),
  };
}

test("a beta build with a round open loads the tuning panel, and production's leaves it out", () => {
  for (const app of listApps()) {
    const { appsRoot, remove } = createTuningRoot(app);
    try {
      const beta = listBundledFiles(app, RELEASE, "beta", appsRoot);
      for (const tag of TUNING_TAGS) assert.ok(tag.test(beta["index.html"].text), `${app}: ${tag}`);
      assert.ok(beta["shared/tuning-panel.js"], app);
      assert.equal(beta["tuning-round.json"], undefined, app);

      const production = listBundledFiles(app, { ...RELEASE, label: null }, "production", appsRoot);
      assert.doesNotMatch(production["index.html"].text, /tuning/i, app);
      for (const file of [
        "shared/tuning-panel.js",
        "shared/tuning-panel.css",
        "shared/tuning-round.js",
        "tuning-round.json",
      ])
        assert.equal(production[file], undefined, `${app} ${file}`);
    } finally {
      remove();
    }
  }
});

// Node has no Workers runtime, so the runtime's own module stands in as its two classes.
const WORKERS_RUNTIME_STAND_IN =
  "data:text/javascript,export class DurableObject {} export class WorkerEntrypoint {}";

/** @param {string} app */
async function loadForbiddingGlobalWork(app) {
  const folder = mkdtempSync(path.join(tmpdir(), `${app}-worker-`));
  const bundlePath = path.join(folder, "worker.mjs");
  const built = await buildWorker(app, { release: RELEASE });
  writeFileSync(
    bundlePath,
    built.replaceAll('"cloudflare:workers"', `"${WORKERS_RUNTIME_STAND_IN}"`),
  );
  /** @param {string} name */
  const refuse = (name) => () => {
    throw new Error(`${app}'s Worker called ${name} while it loads`);
  };
  // Cloudflare refuses a Worker whose modules, as they load, do any of these.
  const mocks = [
    mock.method(globalThis, "fetch", refuse("fetch")),
    mock.method(globalThis, "setTimeout", refuse("setTimeout")),
    mock.method(globalThis, "setInterval", refuse("setInterval")),
    mock.method(crypto, "getRandomValues", refuse("getRandomValues")),
    mock.method(crypto, "randomUUID", refuse("randomUUID")),
  ];
  try {
    return await import(pathToFileURL(bundlePath).href);
  } finally {
    for (const forbidden of mocks) forbidden.mock.restore();
    rmSync(folder, { recursive: true });
  }
}

test("each app's Worker loads without what Cloudflare refuses while a Worker loads", async () => {
  for (const app of listApps()) {
    const worker = await loadForbiddingGlobalWork(app);
    assert.equal(typeof worker.default.fetch, "function", app);
  }
});

test("a service's Worker loads its packages as a Worker resolves them, importing only the runtime", async () => {
  for (const service of listServices()) {
    const built = await buildWorker(service, { release: RELEASE });
    const imports = [...built.matchAll(/^import .* from "([^"]+)";$/gm)].map(([, from]) => from);
    assert.deepEqual([...new Set(imports)], ["cloudflare:workers"], service);
    const worker = await loadForbiddingGlobalWork(service);
    assert.equal(typeof worker.default, "function", service);
  }
});

test("a beta release with no version to count from still says beta", () => {
  const git = createGit({ "log -1 --format=%h": "b102733\n" });
  assert.equal(readRelease("mlb", git, BUILT_AT, "beta")?.version, "b102733-beta");
});
